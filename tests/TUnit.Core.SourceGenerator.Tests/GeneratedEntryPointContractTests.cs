    [Test]
    public async Task ClosedWorldRootCallGraphUsesTypedCaseDelegates()
    {
        const string source = """
            using TUnit.Core;
            namespace TestProject;
            public sealed class DirectCallGraphFixture
            {
                [Test]
                [Arguments(7)]
                public void Case(long value) { }
            }
            """;

        var build = BuildGeneratedCatalog(source, closedWorld: true);
        var entryPoint = build.Assembly.GetType("TUnit.Generated.GeneratedTestEntryPoint")!;
        var directCatalog = (ITestEntryCatalog) entryPoint
            .GetMethod("GetCatalog", BindingFlags.Public | BindingFlags.Static)!
            .Invoke(null, null)!;
        await Assert.That(directCatalog.GetGeneratedCases()).IsNotEmpty();
        var roots = new MethodBase?[]
        {
            entryPoint.GetMethod("GetCatalog", BindingFlags.Public | BindingFlags.Static),
            entryPoint.GetMethod("GetCatalogAsync", BindingFlags.Public | BindingFlags.Static),
            entryPoint.TypeInitializer,
        }.OfType<MethodBase>();
        var visited = new HashSet<MethodBase>();
        var pending = new Queue<MethodBase>(roots);
        var forbidden = new List<string>();

        while (pending.Count > 0)
        {
            var method = pending.Dequeue();
            if (!visited.Add(method))
            {
                continue;
            }

            foreach (var member in GetReferencedMembers(method))
            {
                var identity = member switch
                {
                    Type type => type.FullName ?? type.Name,
                    MethodBase referencedMethod => referencedMethod.DeclaringType?.FullName + "." + referencedMethod.Name,
                    _ => member.DeclaringType?.FullName + "." + member.Name,
                };
                if (IsDesktopActivationSymbol(identity))
                {
                    forbidden.Add(identity);
                }

                if (member is MethodBase referenced && referenced.DeclaringType?.Assembly == build.Assembly)
                {
                    pending.Enqueue(referenced);
                }
            }
        }

        await Assert.That(forbidden).IsEmpty()
            .Because(string.Join(Environment.NewLine, forbidden));
    }

