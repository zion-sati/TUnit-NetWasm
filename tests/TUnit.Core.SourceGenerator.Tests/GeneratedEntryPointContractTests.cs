    private static IEnumerable<MemberInfo> GetReferencedMembers(MethodBase method)
    {
        var body = method.GetMethodBody();
        var il = body?.GetILAsByteArray();
        if (il is null)
        {
            yield break;
        }

        var singleByteOpCodes = new OpCode[0x100];
        var doubleByteOpCodes = new OpCode[0x100];
        foreach (var field in typeof(OpCodes).GetFields(BindingFlags.Public | BindingFlags.Static))
        {
            if (field.GetValue(null) is not OpCode opCode)
            {
                continue;
            }

            var value = unchecked((ushort) opCode.Value);
            if (value < 0x100)
            {
                singleByteOpCodes[value] = opCode;
            }
            else if ((value & 0xff00) == 0xfe00)
            {
                doubleByteOpCodes[value & 0xff] = opCode;
            }
        }

        var module = method.Module;
        var typeArguments = method.DeclaringType?.IsGenericType == true
            ? method.DeclaringType.GetGenericArguments()
            : null;
        var methodArguments = method is MethodInfo { IsGenericMethod: true } genericMethod
            ? genericMethod.GetGenericArguments()
            : null;
        var offset = 0;
        while (offset < il.Length)
        {
            var opCode = il[offset++] == 0xfe
                ? doubleByteOpCodes[il[offset++]]
                : singleByteOpCodes[il[offset - 1]];
            switch (opCode.OperandType)
            {
                case OperandType.InlineMethod:
                case OperandType.InlineField:
                case OperandType.InlineType:
                case OperandType.InlineTok:
                    {
                        var token = BitConverter.ToInt32(il, offset);
                        offset += 4;
                        MemberInfo? member = null;
                        try
                        {
                            member = opCode.OperandType switch
                            {
                                OperandType.InlineMethod => module.ResolveMethod(token, typeArguments, methodArguments),
                                OperandType.InlineField => module.ResolveField(token, typeArguments, methodArguments),
                                OperandType.InlineType => module.ResolveType(token, typeArguments, methodArguments),
                                _ => module.ResolveMember(token, typeArguments, methodArguments),
                            };
                        }
                        catch (ArgumentException)
                        {
                            // A token that belongs to an unresolved external generic reference is
                            // not a generated call edge and can be ignored by this graph check.
                        }

                        if (member is not null)
                        {
                            yield return member;
                        }

                        if (opCode.OperandType == OperandType.InlineMethod && member is MethodBase referenced)
                        {
                            yield return referenced;
                        }

                        break;
                    }
                case OperandType.InlineI:
                case OperandType.InlineBrTarget:
                case OperandType.InlineString:
                case OperandType.InlineSig:
                case OperandType.InlineVar:
                    offset += opCode.OperandType == OperandType.InlineVar ? 2 : 4;
                    break;
                case OperandType.ShortInlineI:
                case OperandType.ShortInlineBrTarget:
                case OperandType.ShortInlineVar:
                    offset += 1;
                    break;
                case OperandType.InlineI8:
                case OperandType.InlineR:
                    offset += 8;
                    break;
                case OperandType.ShortInlineR:
                    offset += 4;
                    break;
                case OperandType.InlineSwitch:
                    {
                        var count = BitConverter.ToInt32(il, offset);
                        offset += 4 + (count * 4);
                        break;
                    }
            }
        }
    }

